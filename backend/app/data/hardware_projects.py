            full_title = f"{dom_name}: {pat_title}"
            full_desc = f"{pat_desc} Designed with production-grade engineering principles for real-world {dom_name.lower()} applications."
            
            # Formulate skills
            req_skills = list(base_skills)
            if pat_diff == "Advanced" and "PCB Design (KiCad)" not in req_skills and len(req_skills) < 6:
                req_skills.append("PCB Design (KiCad)")
            if "TinyML" in pat_title and "TinyML" not in req_skills:
                req_skills.append("TinyML")
            if "CAN" in pat_title and "CAN Bus" not in req_skills:
                req_skills.append("CAN Bus")
            if "LoRa" in pat_title and "LoRaWAN" not in req_skills:
                req_skills.append("LoRaWAN")
            if "BLE" in pat_title and "BLE (Bluetooth Low Energy)" not in req_skills:
                req_skills.append("BLE (Bluetooth Low Energy)")
            if "FPGA" in pat_title and "FPGA / Verilog" not in req_skills:
                req_skills.append("FPGA / Verilog")

            # Calculate balanced skill weights
            w = {}
            eq = round(1.0 / len(req_skills), 2)
            for i, sk in enumerate(req_skills):
                w[sk] = eq if i < len(req_skills) - 1 else round(1.0 - eq * (len(req_skills) - 1), 2)

            prog_langs = [s for s in req_skills if s in ["Embedded C", "C++", "Python", "JavaScript", "TypeScript", "Verilog", "VHDL"]]
            if not prog_langs:
                prog_langs = ["Embedded C" if "Embedded" in dom_name or "Hardware" in dom_name else "C++"]

